/** ローカル日付ベースの通し日数（同一日なら同じ値） */
function dayNumber(date: Date): number {
  return Math.floor((date.getTime() - date.getTimezoneOffset() * 60_000) / 86_400_000);
}

/** その日のセリフを返す（locale: "en" のみ英語、その他は日本語） */
export function dailyLine(locale: string, date: Date = new Date()): string {
  const lines = locale === "en" ? EN_LINES : JP_LINES;
  const i = ((dayNumber(date) % lines.length) + lines.length) % lines.length;
  return lines[i];
}

